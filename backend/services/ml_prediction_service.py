"""
Machine Learning Prediction Service for ASHA Voice.
Loads and serves the three trained Random Forest models:
  - Pregnancy Risk Model
  - Newborn Risk Model
  - Immunization Risk Model

Features:
  - Safe mapping from existing beneficiary/visit data dictionaries into model feature vectors.
  - Transparent probability score and risk categorization.
  - Explicit explanation of key contributing clinical drivers.
  - Missingness handling: does not assume low-risk if critical vitals are missing.
  - Clinical Safety Priority: NEVER overrides or downgrades deterministic danger signs.
  - Mandatory disclaimer on all outputs: experimental advisory based on synthetic training data.
"""

import os
import json
import logging
import re
from typing import Dict, Any, Optional, List
import pandas as pd
import numpy as np
import joblib

logger = logging.getLogger(__name__)

BASE_DIR = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
MODELS_DIR = os.path.join(BASE_DIR, "ml_models")
ANTIGENS = ["BCG", "OPV", "HepB", "Pentavalent", "Rotavirus", "fIPV", "PCV", "MR", "JE", "Vitamin-A", "DPT"]

SAFETY_DISCLAIMER = (
    "EXPERIMENTAL ML PREDICTION ONLY: This assessment was generated by a Random Forest model trained "
    "on synthetic, clinically unvalidated datasets. It represents an advisory clinical concern screening flag, "
    "NOT a medical diagnosis. It MUST NEVER override or downgrade deterministic emergency danger alerts."
)


class MLPredictionService:
    """Singleton service to manage model loading and prediction inference."""

    _instance = None
    _models: Dict[str, Any] = {}
    _metadata: Optional[Dict[str, Any]] = None

    def __new__(cls):
        if cls._instance is None:
            cls._instance = super().__new__(cls)
            cls._instance._load_models()
        return cls._instance

    def _load_models(self):
        """Loads serialized models and metadata into memory."""
        try:
            meta_path = os.path.join(MODELS_DIR, "model_metadata.json")
            if os.path.exists(meta_path):
                with open(meta_path, "r") as f:
                    self._metadata = json.load(f)

            for key, filename in [
                ("pregnancy", "pregnancy_rf_model.joblib"),
                ("newborn", "newborn_rf_model.joblib"),
                ("immunization", "immunization_rf_model.joblib"),
            ]:
                model_path = os.path.join(MODELS_DIR, filename)
                if os.path.exists(model_path):
                    self._models[key] = joblib.load(model_path)
                    logger.info(f"Loaded ML model: {filename}")
                else:
                    logger.warning(f"ML model file not found: {model_path}")
        except Exception as e:
            logger.error(f"Error loading ML models: {e}")

    def get_metadata(self) -> dict:
        return self._metadata or {}

    def normalize_category(self, category: str) -> str:
        """Normalizes various category strings to pregnancy, newborn, or immunization."""
        c = str(category or "").strip().lower().replace("-", "_")
        if any(w in c for w in ("preg", "maternal", "mother", "anc")):
            return "pregnancy"
        if any(w in c for w in ("newborn", "neonat", "infant", "baby")):
            return "newborn"
        if any(w in c for w in ("immuni", "child", "vaccin")):
            return "immunization"
        return "pregnancy"  # fallback default

    def _lookup(self, data: Dict[str, Any], *keys: str, default: Any = None) -> Any:
        """Case-insensitive and underscore-insensitive lookup for field keys."""
        if not data:
            return default
        norm_map = {str(k).lower().replace("_", "").replace("-", ""): v for k, v in data.items()}
        for k in keys:
            norm_k = str(k).lower().replace("_", "").replace("-", "")
            if norm_k in norm_map and norm_map[norm_k] not in (None, "", "null", "nan"):
                return norm_map[norm_k]
        return default

    def _extract_bp(self, raw_bp: Any, sys_raw: Any, dia_raw: Any):
        """Extracts systolic and diastolic BP from numeric fields or compound strings like '130/90'."""
        sys_val = None
        dia_val = None

        if sys_raw is not None and str(sys_raw).strip() != "":
            try:
                sys_val = float(sys_raw)
            except (ValueError, TypeError):
                pass
        if dia_raw is not None and str(dia_raw).strip() != "":
            try:
                dia_val = float(dia_raw)
            except (ValueError, TypeError):
                pass

        if (sys_val is None or dia_val is None) and raw_bp:
            m = re.findall(r"\b(\d{2,3})\s*[/,\-]\s*(\d{2,3})\b", str(raw_bp))
            if m:
                sys_val = float(m[0][0])
                dia_val = float(m[0][1])

        return sys_val, dia_val

    def _extract_float(self, val: Any) -> Optional[float]:
        if val is None or str(val).strip() in ("", "None", "null", "nan"):
            return None
        try:
            return float(val)
        except (ValueError, TypeError):
            nums = re.findall(r"[-+]?\d*\.?\d+", str(val))
            if nums:
                return float(nums[0])
        return None

    def _normalize_cat(self, val: Any, default: str = "Unknown") -> str:
        if val is None or str(val).strip() in ("", "None", "null", "nan"):
            return default
        s = str(val).strip()
        # Capitalize standardized values
        if s.lower() in ("yes", "true", "present", "positive"):
            return "Yes"
        if s.lower() in ("no", "false", "absent", "negative", "nil", "none"):
            return "No"
        if s.lower() in ("unknown", "unspecified", "not recorded"):
            return "Unknown"
        return s

    def build_pregnancy_features(self, data: Dict[str, Any]) -> pd.DataFrame:
        sys_bp, dia_bp = self._extract_bp(
            self._lookup(data, "blood_pressure", "bp", "vitals_bp"),
            self._lookup(data, "systolic_bp", "Systolic_BP_mmHg", "blood_pressure_systolic"),
            self._lookup(data, "diastolic_bp", "Diastolic_BP_mmHg", "blood_pressure_diastolic"),
        )

        row = {
            "Gestational_Age_Weeks": self._extract_float(self._lookup(data, "gestational_age_weeks", "pregnancy_month", "gestational_age")),
            "Pre_Pregnancy_BMI": self._extract_float(self._lookup(data, "pre_pregnancy_bmi", "bmi")),
            "Current_Weight_kg": self._extract_float(self._lookup(data, "current_weight_kg", "weight_kg", "weight")),
            "Systolic_BP_mmHg": sys_bp,
            "Diastolic_BP_mmHg": dia_bp,
            "Haemoglobin_g_dL": self._extract_float(self._lookup(data, "haemoglobin_g_dl", "haemoglobin", "hb_level", "hb")),
            "Blood_Sugar_mg_dL": self._extract_float(self._lookup(data, "blood_sugar_mg_dl", "blood_sugar_level", "blood_sugar", "sugar")),
            "BP_Reading_Interval_Min": self._extract_float(self._lookup(data, "bp_reading_interval_min", default=15.0)),
            "Glucose_Load_Grams": self._extract_float(self._lookup(data, "glucose_load_grams", default=75.0)),
            "Time_After_Glucose_Load_Hr": self._extract_float(self._lookup(data, "time_after_glucose_load_hr", default=2.0)),
            "Vaginal_Bleeding": self._normalize_cat(self._lookup(data, "vaginal_bleeding", "bleeding")),
            "Severe_Headache_or_Blurred_Vision": self._normalize_cat(
                self._lookup(data, "severe_headache_or_blurred_vision", "severe_headache_blurred_vision", "headache")
            ),
            "Fetal_Movement": self._normalize_cat(self._lookup(data, "fetal_movement"), default="Unknown"),
            "IFA_Calcium_Consumption": self._normalize_cat(self._lookup(data, "ifa_calcium_consumption", "ifa_consumption"), default="Regular"),
            "BP_Repeat_Status": str(self._lookup(data, "bp_repeat_status", default="Not Required")),
            "Blood_Sugar_Test_Context": str(self._lookup(data, "blood_sugar_test_context", default="Random Blood Sugar")),
            "Blood_Sugar_Sample_Type": str(self._lookup(data, "blood_sugar_sample_type", default="Capillary")),
            "Weight_Context_Status": str(self._lookup(data, "weight_context_status", default="Context Present (Serial Review)")),
        }

        # Handle fetal movement standard mapping
        fm = str(row["Fetal_Movement"]).lower()
        if "normal" in fm:
            row["Fetal_Movement"] = "Normal"
        elif "absent" in fm or "reduced" in fm or "decreased" in fm:
            row["Fetal_Movement"] = "Absent"
        elif "unknown" in fm or row["Fetal_Movement"] in ("None", ""):
            row["Fetal_Movement"] = "Unknown"

        # Handle IFA calcium
        ifa = str(row["IFA_Calcium_Consumption"]).lower()
        if "irregular" in ifa or "miss" in ifa:
            row["IFA_Calcium_Consumption"] = "Irregular"
        elif "regular" in ifa:
            row["IFA_Calcium_Consumption"] = "Regular"

        return pd.DataFrame([row])

    def build_newborn_features(self, data: Dict[str, Any]) -> pd.DataFrame:
        row = {
            "Age_Days": self._extract_float(self._lookup(data, "age_days", "age", default=1.0)) or 1.0,
            "Birth_Weight_kg": self._extract_float(self._lookup(data, "birth_weight_kg", "birth_weight")),
            "Current_Weight_kg": self._extract_float(self._lookup(data, "current_weight_kg", "weight_kg", "weight")),
            "Body_Temperature_C": self._extract_float(
                self._lookup(data, "body_temperature_c", "temperature_celsius", "temperature", "temp")
            ),
            "Respiratory_Rate_bpm": self._extract_float(self._lookup(data, "respiratory_rate_bpm", "respiratory_rate", "resp_rate")),
            "Breastfeeding_Status": str(self._lookup(data, "breastfeeding_status", default="Exclusive")),
            "Difficulty_in_Feeding": self._normalize_cat(self._lookup(data, "difficulty_in_feeding", "feeding_difficulty")),
            "Difficulty_in_Breathing": self._normalize_cat(self._lookup(data, "difficulty_in_breathing", "breathing_difficulty")),
            "Yellowing_of_Skin_or_Eyes": str(
                self._lookup(data, "yellowing_of_skin_or_eyes", "yellowing_skin_eyes", "jaundice", default="None")
            ),
            "Umbilical_Cord_Condition": self._normalize_cat(self._lookup(data, "umbilical_cord_condition", "cord_condition"), default="Normal"),
            "Temp_Measurement_Method": str(self._lookup(data, "temp_measurement_method", default="Axillary")),
        }

        # Normalize Breastfeeding
        bf = str(row["Breastfeeding_Status"]).lower()
        if "not" in bf or "bottle" in bf or "formula" in bf:
            row["Breastfeeding_Status"] = "Not breastfeeding"
        else:
            row["Breastfeeding_Status"] = "Exclusive"

        # Normalize Umbilical Cord
        uc = str(row["Umbilical_Cord_Condition"]).lower()
        if "abnormal" in uc or "red" in uc or "pus" in uc or "discharge" in uc:
            row["Umbilical_Cord_Condition"] = "Abnormal"
        elif "normal" in uc or "clean" in uc or "dry" in uc:
            row["Umbilical_Cord_Condition"] = "Normal"

        return pd.DataFrame([row])

    def build_immunization_features(self, data: Dict[str, Any]) -> pd.DataFrame:
        due_raw = str(self._lookup(data, "vaccines_due_today", "vaccines_due", default="") or "")
        given_raw = str(self._lookup(data, "vaccines_given_today", "vaccines_administered_today", "vaccines_given", default="") or "")

        # Split helper
        def split_v(s):
            if not s or s.lower() in ("none", "nan", "", "none (deferred due to acute illness)"):
                return []
            return [x.strip() for x in s.split(",") if x.strip()]

        due_list = split_v(due_raw)
        given_list = split_v(given_raw)

        count_due = float(len(due_list))
        count_given = float(len(given_list))
        deferred = 1.0 if "deferred" in given_raw.lower() else 0.0
        overdue = 1.0 if "overdue" in due_raw.lower() else 0.0

        if deferred:
            deficit = count_due
        else:
            clean_due = {d.replace("(Overdue)", "").strip() for d in due_list}
            clean_given = {g.strip() for g in given_list}
            deficit = float(len(clean_due - clean_given))

        row = {
            "Age_Months": self._extract_float(self._lookup(data, "age_months", "age", default=2.0)) or 2.0,
            "Current_Weight_kg": self._extract_float(self._lookup(data, "current_weight_kg", "weight_kg", "weight")),
            "Current_Height_Length_cm": self._extract_float(self._lookup(data, "current_height_length_cm", "height_cm", "height")),
            "WAZ_Score": self._extract_float(self._lookup(data, "waz_score", default=0.0)) or 0.0,
            "HAZ_Score": self._extract_float(self._lookup(data, "haz_score", default=0.0)) or 0.0,
            "WHZ_Score": self._extract_float(self._lookup(data, "whz_score", default=0.0)) or 0.0,
            "count_vaccines_due": count_due,
            "count_vaccines_given": count_given,
            "dose_deficit_count": deficit,
            "vaccines_deferred": deferred,
            "has_overdue_vaccine": overdue,
            "Gender": str(self._lookup(data, "gender", default="Female")).capitalize(),
            "General_Health_Condition": str(self._lookup(data, "general_health_condition", default="Normal")),
            "Missed_Vaccination_Doses": self._normalize_cat(self._lookup(data, "missed_vaccination_doses")),
            "Previous_AEFI": str(self._lookup(data, "previous_aefi", default="None reported")),
            "Growth_Reference_Indicator": str(self._lookup(data, "growth_reference_indicator", default="WHO Child Growth Standards (WAZ / HAZ / WHZ)")),
        }

        # Add multi-hot antigen flags
        for antigen in ANTIGENS:
            clean = antigen.replace("-", "_").lower()
            row[f"due_{clean}"] = 1.0 if antigen.lower() in due_raw.lower() else 0.0
            row[f"given_{clean}"] = 1.0 if antigen.lower() in given_raw.lower() else 0.0

        return pd.DataFrame([row])

    def explain_prediction(self, category: str, features_df: pd.DataFrame, proba: float) -> List[str]:
        """Generates clear, human-understandable clinical driver explanations."""
        explanations = []
        r = features_df.iloc[0]

        if category == "pregnancy":
            hb = r.get("Haemoglobin_g_dL")
            if hb is not None and not np.isnan(hb):
                if hb < 7.0:
                    explanations.append(f"Severe Anemia flagged: Haemoglobin is critically low at {hb} g/dL (reference >= 11 g/dL).")
                elif hb < 11.0:
                    explanations.append(f"Mild/Moderate Anemia flagged: Haemoglobin is {hb} g/dL (reference >= 11 g/dL).")

            sys_bp = r.get("Systolic_BP_mmHg")
            dia_bp = r.get("Diastolic_BP_mmHg")
            if sys_bp is not None and dia_bp is not None and not (np.isnan(sys_bp) or np.isnan(dia_bp)):
                if sys_bp >= 140 or dia_bp >= 90:
                    explanations.append(f"Elevated Blood Pressure: {int(sys_bp)}/{int(dia_bp)} mmHg exceeds normal threshold (140/90).")

            if r.get("Vaginal_Bleeding") == "Yes":
                explanations.append("Vaginal bleeding reported during pregnancy.")
            if r.get("Severe_Headache_or_Blurred_Vision") == "Yes":
                explanations.append("Severe headache or blurred vision reported (pre-eclampsia symptom).")
            if r.get("Fetal_Movement") == "Absent":
                explanations.append("Absent or significantly reduced fetal movement noted.")

            bs = r.get("Blood_Sugar_mg_dL")
            if bs is not None and not np.isnan(bs) and bs >= 140:
                explanations.append(f"Elevated blood sugar level: {bs} mg/dL requires gestational diabetes screening.")

        elif category == "newborn":
            temp = r.get("Body_Temperature_C")
            if temp is not None and not np.isnan(temp):
                if temp > 37.5:
                    explanations.append(f"Neonatal fever: Temperature {temp}°C exceeds 37.5°C.")
                elif temp < 36.5:
                    explanations.append(f"Neonatal hypothermia: Temperature {temp}°C is below 36.5°C.")

            rr = r.get("Respiratory_Rate_bpm")
            if rr is not None and not np.isnan(rr) and (rr > 60 or rr < 30):
                explanations.append(f"Abnormal respiratory rate: {rr} breaths/min (normal 30-60).")

            if r.get("Difficulty_in_Breathing") == "Yes":
                explanations.append("Difficulty in breathing observed.")
            if r.get("Difficulty_in_Feeding") == "Yes":
                explanations.append("Difficulty or poor feeding reported.")
            jaundice_val = str(r.get("Yellowing_of_Skin_or_Eyes") or "").strip().lower()
            if jaundice_val not in ("none", "no", "unknown", "nan", ""):
                explanations.append(f"Jaundice/yellowing of skin or eyes observed ({r.get('Yellowing_of_Skin_or_Eyes')}).")
            if r.get("Umbilical_Cord_Condition") == "Abnormal":
                explanations.append("Abnormal umbilical cord condition (redness/discharge).")

        elif category == "immunization":
            waz = r.get("WAZ_Score")
            if waz is not None and not np.isnan(waz) and waz < -2.0:
                explanations.append(f"Growth faltering (WAZ Score {waz}): indicates underweight condition.")

            haz = r.get("HAZ_Score")
            if haz is not None and not np.isnan(haz) and haz < -2.0:
                explanations.append(f"Chronic growth deficit (HAZ Score {haz}): indicates stunting.")

            deficit = r.get("dose_deficit_count", 0)
            if deficit > 0:
                explanations.append(f"Vaccine dose deficit: {int(deficit)} due dose(s) were missed or deferred.")

            if r.get("Missed_Vaccination_Doses") == "Yes":
                explanations.append("Caregiver reported missed prior vaccination doses.")

            if str(r.get("General_Health_Condition")).lower() == "unwell":
                explanations.append("Child presented acutely unwell during visit.")

        if not explanations:
            if proba >= 0.5:
                explanations.append("Combined subtle biomarker deviations contributed to elevated clinical concern probability.")
            else:
                explanations.append("All observed maternal and child health indicators remain within standard expected thresholds.")

        return explanations

    def predict(
        self,
        category: str,
        record: Dict[str, Any],
        existing_danger_alert: bool = False,
    ) -> Dict[str, Any]:
        """
        Executes prediction for a beneficiary/visit record.
        Maintains clinical safety: ML cannot downgrade or cancel an existing clinical danger alert.
        """
        cat_key = self.normalize_category(category)
        pipeline = self._models.get(cat_key)

        if pipeline is None:
            return {
                "success": False,
                "error": f"No trained Random Forest model available for category '{cat_key}'.",
                "safety_disclaimer": SAFETY_DISCLAIMER,
            }

        # Build appropriate feature dataframe
        if cat_key == "pregnancy":
            features_df = self.build_pregnancy_features(record)
            model_display_name = "Pregnancy Risk Model (Random Forest)"
        elif cat_key == "newborn":
            features_df = self.build_newborn_features(record)
            model_display_name = "Newborn Risk Model (Random Forest)"
        else:
            features_df = self.build_immunization_features(record)
            model_display_name = "Immunization Risk Model (Random Forest)"

        # Check information completeness / missingness count
        total_cols = features_df.shape[1]
        missing_count = int(features_df.isna().sum().sum())
        completeness_ratio = round(1.0 - (missing_count / total_cols), 2)

        try:
            pred_class = int(pipeline.predict(features_df)[0])
            pred_probs = pipeline.predict_proba(features_df)[0]
            prob_concern = round(float(pred_probs[1]), 4)
            prob_standard = round(float(pred_probs[0]), 4)
        except Exception as e:
            logger.error(f"Inference failure for {cat_key}: {e}")
            return {
                "success": False,
                "error": f"Inference execution failed: {str(e)}",
                "safety_disclaimer": SAFETY_DISCLAIMER,
            }

        # Human-readable label
        if pred_class == 1 or prob_concern >= 0.50:
            pred_label = "Elevated Concern / Potential Risk"
            severity = "warning"
        else:
            pred_label = "Standard / Expected Range"
            severity = "normal"

        # Generate clinical explanations
        explanations = self.explain_prediction(cat_key, features_df, prob_concern)

        # Enforce Clinical Safety Priority
        # If deterministic rules already flagged danger, ensure composite status reflects emergency
        composite_status = pred_label
        if existing_danger_alert:
            composite_status = "CRITICAL EMERGENCY (Clinical Alert Preserved)"
            severity = "emergency"

        return {
            "success": True,
            "category": cat_key,
            "model_name": model_display_name,
            "prediction": pred_class,
            "prediction_label": pred_label,
            "composite_status": composite_status,
            "severity": severity,
            "probability_clinical_concern": prob_concern,
            "probability_standard_risk": prob_standard,
            "information_completeness_ratio": completeness_ratio,
            "clinical_explanations": explanations,
            "clinical_rules_override_prevented": existing_danger_alert,
            "safety_disclaimer": SAFETY_DISCLAIMER,
        }


# Singleton instance exported for backend use
ml_prediction_service = MLPredictionService()
