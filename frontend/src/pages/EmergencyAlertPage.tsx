import { useEffect, useState } from 'react'
import { AlertTriangle, CheckCircle2 } from 'lucide-react'
import { alertAPI } from '../services/api'

interface Alert {
  _id?: string; beneficiary_name?: string; beneficiary_id?: string
  danger_signs?: string[]; referral_status?: string; resolved?: boolean
  created_at?: string
  danger_details?: {rule_id: string; name: string; severity: string}[]
}

export default function EmergencyAlertPage() {
  const [alerts, setAlerts] = useState<Alert[]>([])
  const [loading, setLoading] = useState(true)

  useEffect(() => {
    alertAPI.list(false).then(r => setAlerts(r.data.results || [])).finally(() => setLoading(false))
  }, [])

  async function markReferred(id?: string) {
    if (!id) return
    await alertAPI.update(id, { referral_status: 'referred', resolved: true })
    setAlerts(as => as.filter(a => a._id !== id))
  }

  return (
    <div className="max-w-3xl mx-auto space-y-5">
      <div className="bg-red-600 text-white rounded-2xl p-5 flex items-center gap-4">
        <AlertTriangle className="w-10 h-10 shrink-0" />
        <div>
          <h2 className="text-xl font-bold">Emergency Alerts</h2>
          <p className="text-red-100 text-sm">{alerts.length} active alert{alerts.length !== 1 ? 's' : ''} requiring attention</p>
        </div>
      </div>

      <div className="bg-orange-50 border border-orange-200 rounded-2xl p-4 text-sm text-orange-800">
        ⚠️ <strong>Disclaimer:</strong> ASHA Voice is a referral-support tool, not a diagnostic system. These alerts are generated by a deterministic rule engine based on WHO and IMNCI guidelines. Always use clinical judgment.
      </div>

      {loading ? <div className="space-y-3">{[...Array(2)].map((_,i) => <div key={i} className="h-32 bg-red-50 rounded-2xl animate-pulse" />)}</div> : (
        <div className="space-y-4">
          {alerts.map((a, i) => (
            <div key={a._id || i} className="bg-white border-2 border-red-200 rounded-2xl p-5 shadow-sm">
              <div className="flex items-start justify-between mb-3">
                <div>
                  <p className="font-bold text-gray-900 text-lg">{a.beneficiary_name}</p>
                  <p className="text-sm text-gray-500">{a.beneficiary_id} · {a.created_at?.slice(0,10)}</p>
                </div>
                <span className={`text-xs px-3 py-1 rounded-full font-medium ${a.referral_status === 'referred' ? 'bg-green-100 text-green-700' : 'bg-red-100 text-red-700'}`}>
                  {a.referral_status || 'pending'}
                </span>
              </div>
              <div className="bg-red-50 rounded-xl p-3 mb-4">
                <p className="text-sm font-medium text-red-800 mb-1">Detected Danger Signs:</p>
                <ul className="list-disc list-inside text-sm text-red-700 space-y-0.5">
                  {a.danger_signs?.map((s, j) => <li key={j}>{s}</li>)}
                </ul>
              </div>
              {a.referral_status !== 'referred' && !a.resolved && (
                <button onClick={() => markReferred(a._id)} className="flex items-center gap-2 px-4 py-2 bg-green-700 text-white rounded-xl text-sm font-medium hover:bg-green-800 transition-colors">
                  <CheckCircle2 className="w-4 h-4" /> Mark as Referred to PHC
                </button>
              )}
            </div>
          ))}
          {alerts.length === 0 && (
            <div className="bg-white rounded-2xl p-12 text-center shadow-sm">
              <CheckCircle2 className="w-10 h-10 text-green-400 mx-auto mb-3" />
              <p className="text-gray-500 font-medium">No active emergency alerts</p>
            </div>
          )}
        </div>
      )}
    </div>
  )
}
